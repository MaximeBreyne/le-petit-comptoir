'use strict';
const {app,BrowserWindow,ipcMain}=require('electron');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const {gameWindowOptions,setupGameWindow}=require('../desktop/game-window.cjs');
const profile=fs.mkdtempSync(path.join(os.tmpdir(),'comptoir-menus-'));
app.setPath('userData',profile);
app.commandLine.appendSwitch('autoplay-policy','no-user-gesture-required');
const timeout=setTimeout(()=>{console.error('Menus checks timed out');app.exit(1)},40000);
app.whenReady().then(async()=>{
 let win;
 try{
  const url=pathToFileURL(path.resolve('dist/index.html')).href;
  const native=setupGameWindow({ipcMain,getWindow:()=>win,trustedUrl:url});
  ipcMain.handle('update:status',()=>({state:'disabled',version:'test',message:'Vérification des menus.'}));
  win=new BrowserWindow({...gameWindowOptions(path.resolve('desktop/preload.cjs')),show:false,webPreferences:{...gameWindowOptions(path.resolve('desktop/preload.cjs')).webPreferences,backgroundThrottling:false}});
  native.attach(win);let closeRequests=0;
  win.on('close',event=>{closeRequests++;event.preventDefault()});
  const errors=[];
  win.webContents.on('console-message',event=>{if(event.level==='error'||event.level===3)errors.push(event.message)});
  await win.loadURL(url);
  const result=await win.webContents.executeJavaScript(`(async()=>{
   const check=(value,message)=>{if(!value)throw Error(message)};
   const click=(action,slot)=>{const selector='[data-menu-action="'+action+'"]'+(slot===undefined?'':'[data-slot="'+slot+'"]');const b=document.querySelector(selector);check(b&&!b.disabled,'Active control '+selector);b.click()};
   const esc=()=>window.dispatchEvent(new KeyboardEvent('keydown',{code:'Escape',key:'Escape',bubbles:true,cancelable:true}));
   const flush=()=>new Promise(resolve=>setTimeout(resolve,60));
   // Control the browser's asynchronous unlock event to reproduce the settings
   // return race without hidden-window pointer-capture permission failures.
   let locked=null,deferUnlock=false;const deferredUnlocks=[];
   Object.defineProperty(document,'pointerLockElement',{configurable:true,get:()=>locked});
   canvas.requestPointerLock=()=>Promise.resolve().then(()=>{locked=canvas;document.dispatchEvent(new Event('pointerlockchange'))});
   document.exitPointerLock=()=>{
    const release=()=>{locked=null;document.dispatchEvent(new Event('pointerlockchange'))};
    if(deferUnlock)deferredUnlocks.push(release);else queueMicrotask(release);
   };
   check(GameMenu.isHome()&&paused&&!GameMenu.hasSession(),'Welcome shown before play');
   check(!$('gameMenu').hidden,'Welcome overlay visible');
   check(document.querySelector('[data-menu-action="continue"]').disabled,'No empty continue');
   save();check(localStorage.getItem('comptoir-bar-v2')===null,'Welcome does not create/overwrite a save');
   click('settings');check($('settingsModal').open&&GameMenu.isHome(),'Settings open from welcome without a game');
   $('settingsClose').click();await flush();
   check(GameMenu.isHome()&&GameMenu.getMode()==='home'&&paused&&!$('settingsModal').open,'Returning from welcome settings stays at welcome');
   click('new');check(GameMenu.getMode()==='play'&&!paused,'New game enters play');
   await flush();check(locked===canvas,'Initial camera lock settled');
   deferUnlock=true;GameMenu.openSettings();
   check(paused&&deferredUnlocks.length===1,'Opening settings queues one intentional unlock');
   $('settingsClose').click();check(GameMenu.getMode()==='play'&&!paused,'Return button resumes immediately');
   deferUnlock=false;for(const release of deferredUnlocks.splice(0))release();await flush();
   check(GameMenu.getMode()==='play'&&!paused&&locked===canvas&&BarInput.isLooking(),'Late unlock after settings does not reopen pause');
   check(document.activeElement===canvas,'Deferred pause-menu focus cannot steal focus after returning to play');
   GameMenu.pause();GameMenu.openSettings();$('settingsClose').click();await flush();
   check(GameMenu.getMode()==='play'&&!paused&&locked===canvas,'Return to game button also resumes when settings came from pause');
   GameMenu.openSettings();await flush();esc();await flush();
   check(GameMenu.getMode()==='play'&&!paused&&locked===canvas,'Escape from settings opened in play returns to play');
   game.open();state.time=1439.9;state.orders=[{id:1,name:'Lucie',recipe:'beer',patience:100}];state.nextId=2;
   for(let i=0;i<100;i++)game.tick(.1);
   check(state.closing&&state.time>1450&&state.orders.length===1,'Closing service continues while the last customer waits');
   const closingTime=state.time;GameMenu.returnHome();
   check(!document.querySelector('[data-menu-action="continue"]').disabled,'Closing service save remains loadable after midnight');
   click('continue');check(state.closing&&state.time===closingTime&&state.orders[0].name==='Lucie','Continue restores the closing service');
   game.s=new Game().s;state=game.s;ui();
   state.cash=173;game.open();game.start('beer');game.step();game.setPour(true);keys.KeyW=true;
   esc();check(GameMenu.getMode()==='pause'&&paused,'Escape opens pause');
   check(!state.prep.pouring&&Object.keys(keys).length===0,'Pause stops pouring and held movement');
   const clock=state.time;frame(performance.now()+100);check(state.time===clock,'Pause stops simulation clock');
   click('save');click('save-slot',1);check(JSON.parse(localStorage.getItem('comptoir-bar-slot-v1-1')).state.cash===173,'Manual save written');
   state.cash=999;click('back');click('load');click('load-slot',1);check(GameMenu.getMode()==='confirm'&&state.cash===999,'Load requires confirmation during a session');
   click('confirm');check(state.cash===173&&!state.prep.pouring&&GameMenu.getMode()==='play','Load restores state and stops pouring');
   localStorage.setItem('comptoir-bar-slot-v1-2',JSON.stringify({schema:1,state:{version:2,cash:'invalid'}}));
   esc();click('load');check(document.querySelector('[data-menu-action="load-slot"][data-slot="2"]').disabled,'Corrupt save is not loadable');
   esc();check(GameMenu.getMode()==='pause','Escape from load returns pause');
   click('settings');check($('settingsModal').open&&paused,'Settings pause the game');
   document.querySelector('[data-bind="forward"]').click();check(capturing==='forward','Binding capture active');
   esc();check(!capturing&&$('settingsModal').open,'Escape cancels capture without leaving settings');
   esc();check(!$('settingsModal').open&&GameMenu.getMode()==='pause','Escape from settings returns pause');
   click('home');check(GameMenu.isHome()&&paused,'Return to welcome');
   const auto=localStorage.getItem('comptoir-bar-v2');state.cash=9999;save();check(localStorage.getItem('comptoir-bar-v2')===auto,'Welcome cannot overwrite checkpoint');
   click('continue');check(state.cash===173&&GameMenu.getMode()==='play','Continue loads existing checkpoint');
   GameMenu.returnHome();click('new');check(GameMenu.getMode()==='confirm','New game confirms replacing automatic save');
   click('cancel');check(GameMenu.isHome(),'Cancel keeps existing game');
   click('new');click('confirm');check(state.cash===260&&GameMenu.getMode()==='play','Confirmed new game resets session');
   check(JSON.parse(localStorage.getItem('comptoir-bar-slot-v1-1')).state.cash===173,'New game preserves manual slots');
   GameMenu.pause();GameMenu.openSettings();document.querySelector('[data-bind="forward"]').click();
   return {savedCash:173,manualSlots:3,homeProtected:true,loadValidated:true,settingsReturn:'resumes with delayed unlock; Escape preserves origin',mode:GameMenu.getMode()};
  })()`);
  // Native Escape reaches settings capture even though Chromium key defaults are suppressed.
  win.webContents.send('game:escape');await new Promise(resolve=>setTimeout(resolve,60));
  assert.equal(await win.webContents.executeJavaScript("!capturing && $('settingsModal').open"),true);
  win.webContents.send('game:escape');await new Promise(resolve=>setTimeout(resolve,60));
  assert.equal(await win.webContents.executeJavaScript("GameMenu.getMode()==='pause' && !$('settingsModal').open"),true);
  assert.equal(win.isFullScreen(),true,'Escape keeps native full screen');
  await win.webContents.executeJavaScript("document.querySelector('[data-menu-action=quit]').click()");
  await new Promise(resolve=>setTimeout(resolve,100));assert.equal(closeRequests,1,'Quit desktop requests ordinary window close');
  assert.ok(await win.webContents.executeJavaScript("!!localStorage.getItem('comptoir-bar-v2')"));
  if(errors.length)throw Error(errors.join('\n'));
  console.log('MENUS OK',JSON.stringify({...result,nativeEscape:true,fullscreen:true,quit:'normal window close'}));
  clearTimeout(timeout);win.destroy();app.exit(0);
 }catch(error){clearTimeout(timeout);console.error(error);win?.destroy();app.exit(1)}
});
